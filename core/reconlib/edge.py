"""Quem respondeu? Aplicação, borda (WAF/CDN) bloqueando, ou borda limitando.

Duas falhas opostas que este módulo evita:
  • falso negativo — um 403 da Cloudflare vira "não vulnerável", mas a aplicação nunca viu a requisição;
  • falso positivo — a página de bloqueio ecoa o caminho/payload e parece uma exposição real.

Regra central: o simples fato de haver CDN na frente (`cf-ray`, `x-amz-cf-id`…) só *identifica* o
fabricante; quem faz a resposta ser da borda é uma marca de *enforcement* (`cf-mitigated`,
`x-amzn-waf`…) ou um texto de bloqueio num status compatível (403/406/419). Um 403 sozinho é
resposta comum de aplicação (autorização) e continua sendo da aplicação.

Também reúne o baseline anti soft-404 por host (caminho aleatório) e a contagem de cobertura
("quantas sondagens chegaram na aplicação").
"""
from __future__ import annotations

import secrets
import threading
from dataclasses import dataclass, field

APPLICATION = "application"
EDGE_BLOCKED = "edge-blocked"
EDGE_THROTTLED = "edge-throttled"

# proxy: aparece em tráfego normal (só identifica) · enforcement: aparece só quando a borda agiu.
_SIGNATURES = (
    ("Cloudflare", ("cf-ray", "__cf_bm", "server: cloudflare"),
     ("cf-mitigated", "attention required! | cloudflare", "error 1020", "cf-chl", "cf-browser-verification")),
    ("AWS WAF", ("x-amz-cf-id", "awselb"), ("x-amzn-waf", "x-amzn-errortype: accessdenied")),
    ("CloudFront", ("x-amz-cf-pop",), ("the request could not be satisfied", "generated by cloudfront")),
    ("Akamai", ("akamaighost", "x-akamai", "akamai-origin-hop"), ("akamai reference", "reference #", "akamai error")),
    ("Imperva/Incapsula", ("incap_ses", "visid_incap", "x-iinfo"), ("incapsula incident", "request unsuccessful")),
    ("F5 BIG-IP ASM", ("bigipserver",), ("x-waf-event", "the requested url was rejected")),
    ("Sucuri", ("x-sucuri-id", "x-sucuri-cache"), ("sucuri website firewall", "access denied - sucuri")),
    ("Fastly", ("x-fastly", "fastly-io"), ("fastly error: security",)),
    ("Azure Front Door", ("x-azure-ref", "x-msedge-ref"), ("the request is blocked",)),
    ("PerimeterX", (), ("_px-captcha", "perimeterx")),
    ("ModSecurity", (), ("mod_security", "modsecurity", "not acceptable!")),
    ("Wordfence", (), ("generated by wordfence", "wordfence")),
)

_BLOCK_PHRASES = (
    "attention required", "request blocked", "access denied", "the requested url was rejected",
    "your request has been blocked", "web application firewall", "security policy",
    "forbidden by rule", "error 1020", "you don't have permission to access",
    "this website is using a security service", "bot detected", "automation tools detected",
)
_CHALLENGE_PHRASES = ("just a moment", "checking your browser", "enable javascript and cookies", "_px-captcha")


@dataclass
class Verdict:
    origin: str = APPLICATION
    vendor: str = ""
    reason: str = "resposta da aplicação"

    @property
    def from_application(self) -> bool:
        return self.origin == APPLICATION

    @property
    def edge(self) -> bool:
        return self.origin != APPLICATION


def _lower_headers(headers) -> str:
    try:
        return "\n".join(f"{str(k).lower()}: {str(v).lower()}" for k, v in (headers or {}).items())
    except Exception:
        return ""


def classify(status, headers, body) -> Verdict:
    """Decide quem escreveu a resposta. Em dúvida, é da aplicação (descartar resposta real esconde achado)."""
    try:
        code = int(status or 0)
    except (TypeError, ValueError):
        code = 0
    hay = _lower_headers(headers)
    raw = body if isinstance(body, (bytes, bytearray)) else str(body or "").encode("utf-8", "ignore")
    text = bytes(raw[:4096]).decode("utf-8", "ignore").lower()

    vendor, signal, enforced = "", "", False
    for name, proxy, enforcement in _SIGNATURES:
        hit = next((m for m in enforcement if m in hay or m in text), None)
        if hit:
            vendor, signal, enforced = name, hit, True
            break
        if not vendor:
            hit = next((m for m in proxy if m in hay), None)
            if hit:
                vendor, signal = name, hit

    if code == 429 or (code in (403, 503) and ("too many requests" in text or "rate limit" in text)):
        return Verdict(EDGE_THROTTLED, vendor, f"HTTP {code} limitando taxa — não diz nada sobre o alvo; repetir mais devagar")
    if code in (503, 403) and any(p in text for p in _CHALLENGE_PHRASES):
        return Verdict(EDGE_THROTTLED, vendor, "desafio de navegador/bot — não é veredito sobre a requisição")

    says_blocked = any(p in text for p in _BLOCK_PHRASES)
    if enforced or (says_blocked and code in (403, 406, 419)):
        who = vendor or "filtro não identificado"
        return Verdict(EDGE_BLOCKED, vendor, f"HTTP {code}: {who} respondeu ({signal or 'texto de bloqueio'}) — a aplicação não viu a requisição")
    return Verdict(APPLICATION, vendor)


# ── baseline anti soft-404 ──────────────────────────────────────────────────────────

def _snippet(body, n: int = 200) -> str:
    raw = body if isinstance(body, (bytes, bytearray)) else str(body or "").encode("utf-8", "ignore")
    return bytes(raw[:512]).decode("utf-8", "ignore")[:n]


def _length(body, headers) -> int:
    h = {str(k).lower(): v for k, v in (headers or {}).items()}
    try:
        n = int(h.get("content-length") or 0)
    except (TypeError, ValueError):
        n = 0
    return n or len(body or b"")


@dataclass
class Baseline:
    """Como o host responde a um caminho que não existe."""
    status: int
    length: int
    snippet: str
    verdict: Verdict = field(default_factory=Verdict)

    @property
    def edge_blocked(self) -> bool:
        """A borda barra até um caminho inexistente: nenhuma sondagem aqui chega na aplicação."""
        return self.verdict.origin == EDGE_BLOCKED

    def matches(self, status, body, headers=None) -> bool:
        """A resposta é igual à do caminho inexistente (SPA/WAF respondendo o mesmo para tudo)?"""
        if status != self.status:
            return False
        snip, length = _snippet(body), _length(body, headers)
        if snip == self.snippet:
            return True
        # páginas grandes variam alguns bytes por requisição (tokens, nonces); pequenas têm de bater no conteúdo
        a, b = length or len(snip), self.length or len(self.snippet)
        return min(a, b) >= 512 and abs(a - b) <= 0.05 * max(a, b)


def fetch_baseline(base_url: str, timeout: int = 5, get=None) -> Baseline | None:
    """Sonda `<base_url>/sctw-<aleatório>`. None = host não respondeu (nada a sondar).
    `get` é o `http_get` do módulo chamador (assim os testes continuam podendo trocá-lo)."""
    if get is None:
        from core.reconlib.base import http_get as get
    status, body, headers = get(f"{base_url.rstrip('/')}/sctw-{secrets.token_hex(5)}",
                                     timeout=timeout, retries=0)
    if not status:
        return None
    return Baseline(status, _length(body, headers), _snippet(body), classify(status, headers, body))


# ── cobertura ───────────────────────────────────────────────────────────────────────

@dataclass
class Coverage:
    """Quantas sondagens chegaram na aplicação. Sem isso, "nada encontrado" atrás de WAF engana."""
    total: int = 0
    reached: int = 0
    blocked: int = 0
    throttled: int = 0
    vendors: set = field(default_factory=set)
    _lock: object = field(default_factory=threading.Lock, repr=False, compare=False)

    def add(self, verdict: Verdict) -> None:
        with self._lock:   # os módulos sondam em várias threads
            self.total += 1
            if verdict.vendor:
                self.vendors.add(verdict.vendor)
            if verdict.origin == APPLICATION:
                self.reached += 1
            elif verdict.origin == EDGE_BLOCKED:
                self.blocked += 1
            else:
                self.throttled += 1

    @property
    def ratio(self) -> float:
        return 1.0 if not self.total else self.reached / self.total

    @property
    def meaningful(self) -> bool:
        """Com menos da metade das sondagens chegando, a ausência de achados não prova nada."""
        return self.ratio >= 0.5

    def as_dict(self) -> dict:
        return {"total": self.total, "reached_application": self.reached, "edge_blocked": self.blocked,
                "edge_throttled": self.throttled, "vendors": sorted(self.vendors),
                "ratio": round(self.ratio, 2), "negatives_meaningful": self.meaningful}


def summarize(by_module: dict) -> dict:
    """Junta a cobertura de vários módulos (`Coverage.as_dict()` de cada um) para relatório e dashboard."""
    mods = {m: c for m, c in (by_module or {}).items() if isinstance(c, dict) and c.get("total")}
    total = sum(c["total"] for c in mods.values())
    reached = sum(c.get("reached_application", 0) for c in mods.values())
    blocked = sum(c.get("edge_blocked", 0) for c in mods.values())
    throttled = sum(c.get("edge_throttled", 0) for c in mods.values())
    vendors = sorted({v for c in mods.values() for v in c.get("vendors", [])})
    ratio = 1.0 if not total else reached / total
    meaningful = ratio >= 0.5
    text = f"{reached}/{total} sondagens chegaram na aplicação ({ratio:.0%}); {blocked} bloqueadas e {throttled} limitadas pela borda"
    if vendors:
        text += f" ({', '.join(vendors)})"
    text += "."
    if not meaningful:
        text += " A maior parte do teste não chegou na aplicação: a ausência de achados aqui NÃO indica que ela é segura."
    return {"total": total, "reached_application": reached, "edge_blocked": blocked, "edge_throttled": throttled,
            "vendors": vendors, "ratio": round(ratio, 2), "negatives_meaningful": meaningful,
            "summary": text, "by_module": mods}
